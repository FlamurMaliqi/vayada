UPDATE booking.booking_guests
SET country_code_raw = NULLIF(BTRIM(country_code), ''),
    country_code_review_required = NULLIF(BTRIM(country_code), '') IS NOT NULL,
    country_code = NULL
WHERE country_code IS NOT NULL
  AND NOT booking.is_supported_nationality_code(country_code);

ALTER TABLE booking.booking_guests
  ADD CONSTRAINT chk_booking_guests_country_supported
    CHECK (country_code IS NULL OR booking.is_supported_nationality_code(country_code))
    NOT VALID;
