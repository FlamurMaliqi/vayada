export type FinanceColumn = readonly [jsonKey: string, sqlName: string, type: string];
export type FinanceTableDefinition = {
  table: string;
  key: readonly string[];
  freshness: string;
  columns: readonly FinanceColumn[];
};

const c = (jsonKey: string, sqlName: string, type: string): FinanceColumn => [
  jsonKey,
  sqlName,
  type,
];
const id = c("id", "id", "uuid");
const property = c("propertyId", "property_id", "uuid");
const created = c("createdAt", "created_at", "timestamptz");
const updated = c("updatedAt", "updated_at", "timestamptz");
const source = (kind: string) =>
  [
    c("sourceSystem", "source_system", "text"),
    c(`source${kind}Id`, `source_${kind.toLowerCase()}_id`, "text"),
  ] as const;

